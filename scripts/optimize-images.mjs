#!/usr/bin/env node
/**
 * Converts photos to self-hosted, responsive WebP.
 *
 * Reads originals from assets/photos/ (plus any licence-cleared URLs listed in
 * assets/photos/sources.json), writes public/images/<name>-<width>.webp at
 * several widths, and regenerates src/data/images.ts so components can
 * reference them with a srcset and intrinsic dimensions.
 *
 * Run it after adding or replacing a photo:  npm run images
 *
 * Only outputs are committed. Originals stay out of git — phone photos are
 * megabytes each and the WebP derivatives are what actually ship.
 *
 * Licensing: sources.json is the record of what may be hosted here. Add a URL
 * to it only if the licence permits self-hosting. iStock preview URLs and
 * Google image thumbnails do not, and copying them onto our own server turns a
 * hotlink into a clearer infringement.
 */
import { readdir, readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, 'assets', 'photos');
const OUT_DIR = path.join(ROOT, 'public', 'images');
const MANIFEST = path.join(ROOT, 'src', 'data', 'images.ts');
const WIDTHS = [480, 768, 1200, 1600];
const QUALITY = 78;

const slugify = (name) =>
  path.parse(name).name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

async function fetchCleared() {
  const file = path.join(SRC_DIR, 'sources.json');
  if (!existsSync(file)) return [];
  const { images = [] } = JSON.parse(await readFile(file, 'utf8'));
  const out = [];
  for (const entry of images) {
    const dest = path.join(SRC_DIR, `${entry.name}.jpg`);
    if (existsSync(dest)) { out.push(dest); continue; }
    try {
      const res = await fetch(entry.url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      await writeFile(dest, Buffer.from(await res.arrayBuffer()));
      console.log(`  fetched ${entry.name} (${entry.license})`);
      out.push(dest);
    } catch (err) {
      console.warn(`  could not fetch ${entry.name}: ${err.message}`);
    }
  }
  return out;
}

await mkdir(OUT_DIR, { recursive: true });
await mkdir(SRC_DIR, { recursive: true });

await fetchCleared();

const originals = (await readdir(SRC_DIR))
  .filter((f) => /\.(jpe?g|png|webp|tiff?|avif)$/i.test(f))
  .sort();

const manifest = {};
let written = 0;

for (const file of originals) {
  const input = path.join(SRC_DIR, file);
  const slug = slugify(file);
  const meta = await sharp(input).metadata();
  // Never upscale, and never exceed the largest configured width — a 4032px
  // phone photo should top out at 1600, not ship a 4032px file nobody needs.
  const usable = WIDTHS.filter((w) => w <= meta.width);
  const sizes = usable.length ? usable : [meta.width];

  const srcRoot = await stat(input);
  for (const w of sizes) {
    const out = path.join(OUT_DIR, `${slug}-${w}.webp`);
    if (existsSync(out) && (await stat(out)).mtimeMs > srcRoot.mtimeMs) continue;
    await sharp(input).resize(w).webp({ quality: QUALITY }).toFile(out);
    written++;
  }

  const largest = sizes[sizes.length - 1];
  manifest[slug] = {
    src: `/images/${slug}-${largest}.webp`,
    srcSet: sizes.map((w) => `/images/${slug}-${w}.webp ${w}w`).join(', '),
    width: largest,
    height: Math.round((meta.height / meta.width) * largest),
  };
}

const body = Object.entries(manifest)
  .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`)
  .join('\n');

await writeFile(
  MANIFEST,
  `/**\n * Generated by scripts/optimize-images.mjs — do not edit by hand.\n *\n`
    + ` * Run \`npm run images\` after adding or replacing anything in assets/photos/.\n */\n\n`
    + `export interface PhotoAsset {\n  src: string;\n  srcSet: string;\n  width: number;\n  height: number;\n}\n\n`
    // Indexed through a Record so the file still typechecks while the catalog is
    // empty (keyof {} is never, which makes photos[name] unusable), while
    // PhotoName stays the literal union of real keys for callers.
    + `const catalog = {\n${body}\n} as const;\n\n`
    + `export const photos: Record<string, PhotoAsset> = catalog;\n\n`
    + `export type PhotoName = keyof typeof catalog;\n`,
);

console.log(
  `optimize-images: ${originals.length} original(s), ${written} webp written, `
    + `${Object.keys(manifest).length} in the manifest`,
);
if (!originals.length) {
  console.log('  assets/photos/ is empty — see its README for what to add.');
}
